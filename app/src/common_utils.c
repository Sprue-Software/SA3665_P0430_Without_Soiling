/****************************************************************************************************//**
*                                       CommonUtils_Uint32ToUint8()
*
* @brief	Convert uint32 value to 4 bytes of uint8 value
*
* @param	u32Data	uint32 value
* @param	u8Buff	uint8 buffer
********************************************************************************************************/
void CommonUtils_Uint32ToUint8(uint32_t u32Data, uint8_t u8Buff[]) {
	u8Buff[0] = (uint8_t)((u32Data & 0xFF000000u) >> 24u);
	u8Buff[1] = (uint8_t)((u32Data & 0x00FF0000u) >> 16u);
	u8Buff[2] = (uint8_t)((u32Data & 0x0000FF00u) >> 8u);
	u8Buff[3] = (uint8_t)(u32Data & 0x000000FFu);
}


/****************************************************************************************************//**
*                                       CommonUtils_Uint32ToUint8_swap() LSB first
*
* @brief  Convert uint32 value to 4 bytes of uint8 value
* @param  u32Data uint8 value
********************************************************************************************************/
void CommonUtils_Uint32ToUint8_swap(uint32_t u32Data, uint8_t u8Buff[]) {
  u8Buff[3] = (uint8_t)((u32Data & 0xFF000000u) >> 24u);
  u8Buff[2] = (uint8_t)((u32Data & 0x00FF0000u) >> 16u);
  u8Buff[1] = (uint8_t)((u32Data & 0x0000FF00u) >> 8u);
  u8Buff[0] = (uint8_t)(u32Data & 0x000000FFu);
}


/****************************************************************************************************//**
*                                       CommonUtils_Uint8ToUint32()
*
* @brief	Convert 4 bytes of uint8 value to uint32 value
* @param	u8Buff	uint8 buffer
* @return	uint32 value
********************************************************************************************************/
uint32_t CommonUtils_Uint8ToUint32(uint8_t u8Buff[]) {
	uint32_t data;


	data =  ((uint32_t)u8Buff[0] << 24u) | ((uint32_t)u8Buff[1] << 16u) | ((uint32_t)u8Buff[2] << 8u) | ((uint32_t)u8Buff[3]);
	return data;
}

/****************************************************************************************************//**
*                                       CommonUtils_Uint16ToUint8()
*
* @brief	Convert uint16 value to 2 bytes of uint8 value
*
* @param	u16Data	uint16 value
* @param	u8Buff	uint8 buffer
********************************************************************************************************/
void CommonUtils_Uint16ToUint8(uint16_t u16Data, uint8_t u8Buff[]) {
	u8Buff[0] = (uint8_t)((u16Data & 0xFF00u) >> 8u);
	u8Buff[1] = (uint8_t)(u16Data & 0x00FFu);
}

/****************************************************************************************************//**
*                                       CommonUtils_Uint16ToUint8_swap()
*
* @brief  Convert uint16 value to 2 bytes of uint8 value
* @param  u16Data uint8 value
* @return NULL
********************************************************************************************************/
void CommonUtils_Uint16ToUint8_swap(uint16_t u16Data, uint8_t u8Buff[]) {
  u8Buff[1] = (uint8_t)((u16Data & 0xFF00u) >> 8u);
  u8Buff[0] = (uint8_t)(u16Data & 0x00FFu);
}

/****************************************************************************************************//**
*                                       CommonUtils_Uint8ToUint16()
*
* @brief	Convert 2 bytes of uint8 value to uint16 value
*
* @param	u8Buff	uint8 buffer
*
* @return	uint16 value
********************************************************************************************************/
uint16_t CommonUtils_Uint8ToUint16(uint8_t u8Buff[]) {
	uint16_t data;


	data =  ((uint16_t)u8Buff[0] << 8u) | (uint16_t)u8Buff[1];
	return data;
}
